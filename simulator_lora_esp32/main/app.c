static const char *__tag_app = "app";

static uint32_t tx_count = 0, tx_errors = 0;

// -----------------------------------------------------------------------------------------------------------------------------------------
// Node personality, one per simulated sensor
//
// A simulator is a fleet in one box, so each virtual sensor keeps its own receive window and they
// drift apart rather than all waking together -- which is what a real fleet does, and the thing
// worth simulating.
//
// One difference from the real sensor: it appends RECEIVE to the telemetry frame it was already
// sending (two bytes), whereas here the frames are built inside the simulator library, so the
// advertisement goes out as a frame of its own immediately afterwards. Same moment, same effect on
// whoever is holding a command -- just an extra frame of airtime that a real node would not spend.
// -----------------------------------------------------------------------------------------------------------------------------------------

static iotsim_t g_sim;
static idep_node_t s_nodes[IOTDATA_CONFIG_SIMULATOR_SENSORS_MAX]; /* dimensioned for the MAX; SIM_SENSORS is live */

static datastore_t s_datastore;
static iotdata_node_state_t s_state;
static iotdata_settings_t s_settings[IOTDATA_CONFIG_SIMULATOR_SENSORS_MAX];
static iotdata_settings_t s_settings_default[IOTDATA_CONFIG_SIMULATOR_SENSORS_MAX]; /* one restore-to image each */
static idep_config_t s_confs[IOTDATA_CONFIG_SIMULATOR_SENSORS_MAX];
#define SIM_SETTINGS_TAG(station) (0x53530000UL | (uint32_t)(station)) /* "SS" + station */

/*
 * A block per virtual station, TAGGED BY STATION rather than by array index.
 *
 * The station ids come from this board's MAC (see app_init), so an index-derived tag would restore
 * one board's sequence onto a different board's station the moment the same image is flashed
 * elsewhere. Keyed by station, a foreign record simply finds no home and that sensor starts clean.
 * Stations are 12-bit, so this is unique and stable per station.
 */
#define SIM_STATE_TAG(station)    (0x53490000UL | (uint32_t)(station)) /* "SI" + station */

static void sim_node_status(const uint16_t station, iotdata_node_status_t *const out) {
    out->uptime_s = (uint32_t)(hw_time_ms() / 1000);
    out->reason = IOTDATA_NODE_REASON_UNKNOWN;
    out->has_heap = true;
    out->heap_free = (uint32_t)esp_get_free_heap_size();
    out->heap_min = (uint32_t)esp_get_minimum_free_heap_size();
    for (int i = 0; i < SIM_SENSORS; i++)
        if (idep_station(&s_nodes[i]) == station) {
            const iotsim_sensor_t *const s = iotsim_sensor(&g_sim, i);
            if (s != NULL) {
                out->has_supply = true;
                out->supply_mv = (uint16_t)(s->battery * 30u); /* % -> a plausible mV */
            }
            break;
        }
}

static bool sim_node_tx(const uint8_t *const packet, const size_t len) {
    if (lora_write_complete(packet, len, /*wait_complete=*/true) == ESP_OK) {
        tx_count++;
        return true;
    } else {
        tx_errors++;
        return false;
    }
}

