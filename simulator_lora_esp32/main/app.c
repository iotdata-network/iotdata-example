static void transmit_packet(const iotsim_packet_t *pkt) {
    static char hex[512];
    hex[0] = '\0';
    for (size_t i = 0, o = 0; i < pkt->len && o < (sizeof(hex) - 1); i++)
        o += (size_t)snprintf(&hex[o], (sizeof(hex) - o) - 1, "%02" PRIX8, pkt->buf[i]);
    ESP_LOGI(__tag_app, "device: e22 tx #%06" PRIu32 ": station=%03" PRIX16 " %-18s seq=%06" PRIu16 " len=%-2" PRIu16 " hex=%s", tx_count, pkt->station_id, iotdata_vsuite_name(pkt->variant), pkt->sequence, (uint16_t)pkt->len, hex);
    if (lora_write_complete(pkt->buf, pkt->len, /*wait_complete=*/true) == ESP_OK)
        tx_count++;
    else {
        tx_errors++;
        ESP_LOGE(__tag_app, "device: e22 tx lora_write_complete failed (errors=%" PRIu32 ")", tx_errors);
    }
}

static void transmit_packets(iotsim_t *const sim) {
    iotsim_packet_t pkt;
    while (iotsim_poll(sim, hw_time_ms(), &pkt)) {
        transmit_packet(&pkt);
        hw_delay_ms_yieldable(TRANSMIT_DELAY_MS);
        const int idx = pkt.sensor_index;
        if (idx >= 0 && idx < SIM_SENSORS)
            idep_sequence_used(&s_nodes[idx]); /* in lockstep with the engine's own advance */
        if (idx >= 0 && idx < SIM_SENSORS && idep_window_pending(&s_nodes[idx])) {
            s_nodes[idx].sequence = (uint16_t)(pkt.sequence + 1u);
            if (idep_receive_announce(&s_confs[idx], &s_nodes[idx])) {
                idep_window_begin(&s_confs[idx], &s_nodes[idx], hw_time_ms());
                ESP_LOGI(__tag_app, "node: station=%03" PRIX16 " receive window open for %ums", idep_station(&s_nodes[idx]), (unsigned)IDEP_RECEIVE_WINDOW_MS);
            }
            hw_delay_ms_yieldable(TRANSMIT_DELAY_MS);
        }
    }
}

